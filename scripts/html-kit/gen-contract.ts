/**
 * Rust side of the markup contract (Phase 1 §4):
 * - `contract_gen.rs`: one module per unit with its class consts and `data-*` value enums, so
 *   hand-written emitters carry no `"cv-…"` literal (gate G4, `tests/contract.rs`).
 * - `emit/auto_gen.rs`: emitters written from anatomy for parts marked `emit: 'auto'`.
 *
 * Auto emitters are deliberately small (no loops, no computed values). What the anatomy cannot
 * say is fixed by these conventions, documented once here and in the generated header:
 * - `when: 'p'` / `'!p'`: prop `p` is true (bool) or set (other kinds); a prop the `.cv` surface
 *   does not have is always false (`!asChild` → always rendered).
 * - `data-x`: from prop `x` (its catalog default when unset, omitted without one; a bool prop
 *   gives `"true"` or nothing). Without a prop `x`, the first value is the resting one and each
 *   later value wins while the bool prop of that name is true (`data-state` idle/loading).
 * - `aria-busy` → `"true"` while `loading`; `aria-hidden` → `"true"`; any other aria-* cannot
 *   be auto-emitted (use `emit: 'manual'`).
 * - A polymorphic `[…, 'a']` element is the `<a>` while `href` is a safe URL and the part is not
 *   disabled. A `button` gets `disabled` while `disabled` or busy.
 * - `$slot` is the node's text (`children: 'text'`) or its child nodes; `$text` in part `k` is
 *   prop `k`; `@unit` calls the hand-written `embed::<unit>` (it decides whether it renders).
 * - Attribute order: role, data-*, aria-*, class (+ modifiers), href, disabled.
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { compileModule } from '../contract/css.ts'
import { rootClass, type ContractUnit } from '../contract/generate.ts'
import { moduleFiles, repoRoot } from './build-css.ts'
import { CV_SPEC } from './cv-spec.ts'

export const CONTRACT_HEADER =
  '// @generated by scripts/html-kit/gen-contract.ts from packages/css/contract.json — do not edit\n'

type Data = string[] | 'string' | 'number' | 'boolean'
export interface Part {
  element: string | string[]
  local: string
  class: string
  data?: Record<string, Data>
  aria?: string[]
  role?: string
  children?: string[]
  when?: string
  emit?: 'auto' | 'manual'
  modifiers?: Record<string, { class: string; when: string }>
}
export interface Unit {
  alias: string
  classes: Record<string, string>
  anatomy?: { root: Part; parts?: Record<string, Part> }
}
export type Units = Record<string, Unit>

const RUST_KEYWORDS = new Set(
  'as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self static struct super trait true type unsafe use where while abstract become box do final macro override priv typeof unsized virtual yield try gen'.split(
    ' ',
  ),
)
const words = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
export const modName = (unit: string): string => {
  const m = words(unit).join('_').toLowerCase()
  return RUST_KEYWORDS.has(m) ? `r#${m}` : m
}
export const constName = (local: string): string => {
  const c = words(local).join('_').toUpperCase()
  return /^\d/.test(c) ? `C_${c}` : c
}
export const pascal = (s: string): string => {
  const p = words(s)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('')
  return /^\d/.test(p) ? `V${p}` : p
}

/** contract.json units plus the cascivo-html units outside it (layouts, charts), by compiled locals. */
export function loadUnits(): Units {
  const json = JSON.parse(readFileSync(join(repoRoot, 'packages/css/contract.json'), 'utf8')) as {
    units: Units
  }
  const units: Units = { ...json.units }
  for (const unit of new Set(CV_SPEC.flatMap((e) => e.css))) {
    if (units[unit]) continue
    const locals = [
      ...new Set(moduleFiles(unit).flatMap((f) => compileModule(f, unit).locals)),
    ].sort()
    units[unit] = {
      alias: `cv-${unit}`,
      classes: Object.fromEntries(locals.map((l) => [l, `cv-${unit}-${l}`])),
    }
  }
  return Object.fromEntries(Object.entries(units).sort(([a], [b]) => (a < b ? -1 : 1)))
}

function enumRs(name: string, attr: string, values: string[]): string[] {
  const variants = values.map((v) => (v === '' ? 'Empty' : pascal(v)))
  if (new Set(variants).size !== variants.length)
    throw new Error(`${name}: ${attr} values collide as Rust variants: ${values.join(', ')}`)
  return [
    `    /// \`${attr}\` values.`,
    '    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]',
    `    pub enum ${name} {`,
    ...variants.map((v) => `        ${v},`),
    '    }',
    `    impl ${name} {`,
    `        pub const ALL: &[Self] = &[${variants.map((v) => `Self::${v}`).join(', ')}];`,
    "        pub const fn as_str(self) -> &'static str {",
    '            match self {',
    ...variants.map((v, i) => `                Self::${v} => ${JSON.stringify(values[i])},`),
    '            }',
    '        }',
    '        pub fn parse(s: &str) -> Option<Self> {',
    '            Self::ALL.iter().copied().find(|v| v.as_str() == s)',
    '        }',
    '    }',
  ]
}

export function genContractRs(units: Units): string {
  const out = [
    CONTRACT_HEADER,
    '//! Markup contract consts: `cv-<unit>-<local>` classes and `data-*` values per unit.',
    '//! `ROOT` is the root part (anatomy root, else a `root` or unit-named local), `ALIAS` the',
    '//! `cv-<unit>` root alias, every other const a CSS-module local.',
    '',
    `pub const CONTRACT_FORMAT: u32 = 1;`,
  ]
  const mods = new Set<string>()
  for (const [unit, u] of Object.entries(units)) {
    const mod = modName(unit)
    if (mods.has(mod)) throw new Error(`unit ${unit}: Rust module ${mod} collides`)
    mods.add(mod)
    const lines: string[] = []
    const consts = new Map<string, string>()
    const add = (n: string, v: string, doc?: string) => {
      const prev = consts.get(n)
      if (prev !== undefined && prev !== v) throw new Error(`unit ${unit}: const ${n} collides`)
      if (prev !== undefined) return
      consts.set(n, v)
      if (doc) lines.push(`    /// ${doc}`)
      lines.push(`    pub const ${n}: &str = ${JSON.stringify(v)};`)
    }
    const root = rootClass(unit, u as unknown as ContractUnit)
    if (root) add('ROOT', root, 'Root part.')
    add('ALIAS', u.alias, 'Root alias class.')
    for (const [local, cls] of Object.entries(u.classes)) add(constName(local), cls)
    const enums = new Set<string>()
    const a = u.anatomy
    if (a) {
      const parts: [string, Part][] = [['root', a.root], ...Object.entries(a.parts ?? {})]
      for (const [k, p] of parts)
        for (const [attr, vals] of Object.entries(p.data ?? {})) {
          if (!Array.isArray(vals)) continue
          const name = (k === 'root' ? '' : pascal(k)) + pascal(attr.replace(/^data-/, ''))
          if (enums.has(name)) throw new Error(`unit ${unit}: enum ${name} collides`)
          enums.add(name)
          lines.push(...enumRs(name, attr, vals))
        }
    }
    out.push('', `/// \`${unit}\``, `pub mod ${mod} {`, ...lines, '}')
  }
  return out.join('\n') + '\n'
}

