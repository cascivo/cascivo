/**
 * Generates the Rust catalog (`catalog_gen.rs`) and the embedded-CSS table (`css_gen.rs`)
 * for crates/cascivo-html from CV_SPEC + the component `*.meta.ts` manifests.
 * Types (CompSpec, ArgSpec, PropSpec, PropKind, Children, ClientJs) live in src/catalog.rs.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { THEME_NAMES, buildAll, repoRoot } from './build-css.ts'
import { CV_SPEC, packagesRoot, unitDirs, type CvEntry } from './cv-spec.ts'
import { genGuide } from './gen-guide.ts'

export const HEADER = '// @generated by scripts/html-kit/gen-rust.ts — do not edit\n'

type MetaProp = { name: string; type: string; default?: string; description?: string }
type Meta = { description?: string; clientJs?: string; props: MetaProp[] }

/** Props the `.cv` surface never exposes: slots, DOM plumbing and callbacks. */
const SKIPPED = new Set(['children', 'className', 'style', 'ref', 'key', 'asChild'])
/** cv-realized client JS differs from the React manifest (tabs are CSS-only; table sort is opt-in). */
const CLIENT_JS_OVERRIDE: Record<string, string> = { tabs: 'none', 'data-table': 'enhancement' }

export type Kind = { t: 'Str' | 'Num' | 'Bool' } | { t: 'Enum'; values: string[] }

const LITERAL = /^(?:'([^']*)'|(-?\d+(?:\.\d+)?))$/

/** Maps a TS prop type to a PropKind, or null when the `.cv` surface cannot express it. */
export function propKind(type: string): Kind | null {
  const parts = type
    .split('|')
    .map((s) => s.trim())
    .filter((s) => s && s !== 'undefined' && s !== 'null')
  if (!parts.length) return null
  const lits = parts.map((p) => LITERAL.exec(p))
  if (lits.every(Boolean)) return { t: 'Enum', values: lits.map((m) => m![1] ?? m![2]!) }
  if (parts.includes('boolean')) return { t: 'Bool' }
  if (parts.every((p) => p === 'number' || LITERAL.test(p))) return { t: 'Num' }
  if (parts.every((p) => p === 'string' || p === 'number' || p === 'ReactNode' || LITERAL.test(p)))
    return { t: 'Str' }
  return null
}

/** First sentence of a description, markdown stripped, at most 80 characters. */
export function summarize(description: string | undefined): string {
  const plain = (description ?? '')
    .replace(/[`*_]/g, '')
    .replace(/\b(e\.g|i\.e)\./g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
  const first = /^.*?[.!?](?=\s+[A-Z]|$)/.exec(plain)?.[0] ?? plain
  const s = first.replace(/\.$/, '')
  return s.length <= 80 ? s : s.slice(0, 79).trimEnd() + '…'
}

/** Rust string literal; JSON escapes are not all valid Rust, so escape by hand. */
export function rs(s: string): string {
  let o = '"'
  for (const ch of s) {
    const c = ch.codePointAt(0)!
    if (ch === '"' || ch === '\\') o += '\\' + ch
    else if (ch === '\n') o += '\\n'
    else if (ch === '\r') o += '\\r'
    else if (ch === '\t') o += '\\t'
    else if (c < 0x20 || c === 0x7f) o += `\\u{${c.toString(16)}}`
    else o += ch
  }
  return o + '"'
}

const strip = (s: string) => s.replace(/^['"]|['"]$/g, '')
const pascal = (s: string) => s[0]!.toUpperCase() + s.slice(1)

async function loadMeta(component: string): Promise<Meta> {
  for (const d of unitDirs(component)) {
    const file = fileURLToPath(new URL(`${d}/${component}.meta.ts`, packagesRoot))
    if (existsSync(file)) return ((await import(file)) as { meta: Meta }).meta
  }
  throw new Error(`no ${component}.meta.ts`)
}

const block = (field: string, rows: string[]): string[] =>
  rows.length ? [`        ${field}: &[`, ...rows, '        ],'] : [`        ${field}: &[],`]

function genEntry(e: CvEntry, meta: Meta): string {
  const argNames = new Set(e.args.map((a) => a.name))
  const seen = new Set<string>()
  const props = meta.props
    .filter((p) => !SKIPPED.has(p.name) && !/^on[A-Z]/.test(p.name) && !argNames.has(p.name))
    .filter((p) => !seen.has(p.name) && seen.add(p.name))
    .flatMap((p) => {
      const k = propKind(p.type)
      return k ? [{ p, k }] : []
    })
  // `.cv`-only props replace any same-named manifest prop the surface cannot express.
  const extra = e.extraProps ?? []
  const extraNames = new Set(extra.map((x) => x.name))
  const kept = props.filter(({ p }) => !extraNames.has(p.name))
  const kind = (k: Kind) =>
    k.t === 'Enum' ? `PropKind::Enum(&[${k.values.map(rs).join(', ')}])` : `PropKind::${k.t}`
  const clientJs = CLIENT_JS_OVERRIDE[e.component] ?? meta.clientJs ?? 'none'
  const lines = [
    '    CompSpec {',
    `        name: ${rs(e.cv)},`,
    `        component: ${rs(e.component)},`,
    `        aliases: &[${e.aliases.map(rs).join(', ')}],`,
    ...block(
      'args',
      e.args.map(
        (a) =>
          `            ArgSpec { name: ${rs(a.name)}, kind: ArgKind::${pascal(a.kind)}, required: ${a.required} },`,
      ),
    ),
    ...block('props', [
      ...kept.map(
        ({ p, k }) =>
          `            PropSpec { name: ${rs(p.name)}, kind: ${kind(k)}, default: ${
            p.default === undefined ? 'None' : `Some(${rs(strip(p.default))})`
          }, summary: ${rs(summarize(p.description))} },`,
      ),
      ...extra.map(
        (x) =>
          `            PropSpec { name: ${rs(x.name)}, kind: PropKind::Bool, default: None, summary: ${rs(x.summary)} },`,
      ),
    ]),
    `        children: Children::${pascal(e.children)},`,
    `        client_js: ClientJs::${pascal(clientJs)},`,
    `        css: &[${e.css.map(rs).join(', ')}],`,
    `        summary: ${rs(summarize(meta.description))},`,
    '    },',
  ]
  return lines.join('\n')
}

/** Every generated file as `relative path (under crates/cascivo-html) -> content`. */
export async function generateAll(): Promise<Map<string, string>> {
  const out = buildAll()
  const sorted = [...CV_SPEC].sort((a, b) => (a.cv < b.cv ? -1 : a.cv > b.cv ? 1 : 0))
  const metas = await Promise.all(sorted.map((e) => loadMeta(e.component)))
  const entries = sorted.map((e, i) => genEntry(e, metas[i]!))
  const guide = genGuide(
    sorted.map((entry, i) => ({ entry, summary: summarize(metas[i]!.description) })),
  )
  out.set('src/guide_gen.rs', HEADER + `pub const GUIDE: &str = ${rs(guide)};\n`)
  out.set(
    'src/catalog_gen.rs',
    HEADER +
      'use crate::catalog::{ArgKind, ArgSpec, Children, ClientJs, CompSpec, PropKind, PropSpec};\n\n' +
      '#[rustfmt::skip]\npub static CATALOG: &[CompSpec] = &[\n' +
      entries.join('\n') +
      '\n];\n',
  )
  const units = [...out.keys()]
    .filter((k) => k.startsWith('assets/css/') && k !== 'assets/css/base.css')
    .map((k) => k.slice('assets/css/'.length, -'.css'.length))
    .sort()
  out.set(
    'src/css_gen.rs',
    HEADER +
      '#[rustfmt::skip]\npub static COMPONENT_CSS: &[(&str, &str)] = &[\n' +
      units.map((u) => `    (${rs(u)}, include_str!("../assets/css/${u}.css")),\n`).join('') +
      '];\n\n' +
      'pub static BASE_CSS: &str = include_str!("../assets/css/base.css");\n\n' +
      '#[rustfmt::skip]\npub static THEMES: &[(&str, &str)] = &[\n' +
      [...THEME_NAMES]
        .sort()
        .map((t) => `    (${rs(t)}, include_str!("../assets/themes/${t}.css")),\n`)
        .join('') +
      '];\n',
  )
  return out
}

export async function writeAll(dir: string): Promise<void> {
  for (const [rel, content] of await generateAll()) {
    const f = join(dir, rel)
    mkdirSync(join(f, '..'), { recursive: true })
    writeFileSync(f, content)
  }
}

if (import.meta.main) await writeAll(join(repoRoot, 'crates/cascivo-html'))
