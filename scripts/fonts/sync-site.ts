/**
 * Copies the Cascivo Sans files the site serves from the font build into
 * `apps/site/public/fonts/cascivo-sans/`, and writes their byte sizes for the download list.
 * Only copies existing build output — it never runs the Python font build.
 *
 * Run: `pnpm fonts:site:sync` (part of `pnpm regen`). Checked by `font-site-sync.test.ts`.
 */
import { copyFileSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { FONT_FILES } from '../../apps/site/src/marketing/pages/cascivo-sans/data.ts'

const ROOT = join(import.meta.dirname, '../..')
const TARGET = join(ROOT, 'apps/site/public/fonts/cascivo-sans')
const SIZES = join(ROOT, 'apps/site/src/marketing/pages/cascivo-sans/sizes.generated.ts')

mkdirSync(TARGET, { recursive: true })
const wanted = new Set(FONT_FILES.map((f) => f.name))
for (const name of readdirSync(TARGET)) {
  if (!wanted.has(name)) rmSync(join(TARGET, name))
}

const lines: string[] = []
for (const f of FONT_FILES) {
  const src = join(ROOT, f.source)
  copyFileSync(src, join(TARGET, f.name))
  lines.push(`  '${f.name}': ${statSync(src).size},`)
}

// Emitted already formatted, so `vp fmt` leaves it alone and re-running this is a no-op.
writeFileSync(
  SIZES,
  [
    '// Generated by scripts/fonts/sync-site.ts — do not edit. Run `pnpm fonts:site:sync`.',
    'export const FONT_SIZES: Record<string, number> = {',
    ...lines,
    '}',
    '',
  ].join('\n'),
)
console.log(`fonts:site:sync — ${FONT_FILES.length} files → ${TARGET}`)
