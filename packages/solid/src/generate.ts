/** Pure: Custom Elements Manifest (2.1) -> `solid-js` JSX.IntrinsicElements augmentation source. */
interface Attr {
  name: string
  type?: { text?: string }
  description?: string
}
interface Evt {
  name: string
  description?: string
}
interface Decl {
  tagName?: string
  attributes?: Attr[]
  events?: Evt[]
  description?: string
}

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null

function decls(manifest: unknown): Decl[] {
  if (!isObj(manifest) || !Array.isArray(manifest['modules'])) return []
  const out: Decl[] = []
  for (const m of manifest['modules'] as unknown[]) {
    if (!isObj(m) || !Array.isArray(m['declarations'])) continue
    for (const d of m['declarations'] as unknown[]) {
      if (isObj(d) && typeof d['tagName'] === 'string') out.push(d as Decl)
    }
  }
  return out
}

const key = (n: string): string => (/^[A-Za-z_$][\w$]*$/.test(n) ? n : `'${n}'`)

const NATIVE = new Set(['input', 'change'])

function eventType(e: Evt): string {
  const m = /`detail: (\{[^`]*\})`/.exec(e.description ?? '')
  return `CustomEvent<${m?.[1] ?? 'unknown'}>`
}

export function generateTypes(manifest: unknown): string {
  const lines = [
    '// Generated by scripts/generate.ts from @cascivo/elements custom-elements.json. Do not edit.',
    "import type { JSX } from 'solid-js'",
    '',
    'type CvAttrs<T> = JSX.HTMLAttributes<HTMLElement> & T',
    '',
    'export interface CvElements {',
  ]
  for (const d of decls(manifest).sort((a, b) => a.tagName!.localeCompare(b.tagName!))) {
    lines.push(`  /** ${(d.description ?? d.tagName!).replace(/\*\//g, '* /')} */`)
    // Formatter style (bare identifier keys, `{}` when empty) so the committed file is a fixed point.
    const members: string[] = []
    for (const a of d.attributes ?? []) members.push(`${key(a.name)}?: ${a.type?.text ?? 'string'}`)
    for (const e of d.events ?? []) {
      if (!NATIVE.has(e.name)) members.push(`'on:${e.name}'?: (event: ${eventType(e)}) => void`)
    }
    lines.push(
      members.length === 0
        ? `  '${d.tagName}': CvAttrs<{}>`
        : `  '${d.tagName}': CvAttrs<{\n${members.map((m) => `    ${m}`).join('\n')}\n  }>`,
    )
  }
  lines.push(
    '}',
    '',
    "declare module 'solid-js' {",
    '  namespace JSX {',
    '    interface IntrinsicElements extends CvElements {}',
    '  }',
    '}',
    '',
  )
  return lines.join('\n')
}
