/**
 * Generates the markup contract from component manifests + CSS modules:
 *
 * - `packages/css/contract.json`: unit → tier, root alias, classes, resolved anatomy.
 * - `packages/css/src/classes.gen.ts`: the typed `classes` map (`classes.button.label`).
 *
 * Deterministic (sorted inputs, no timestamps). Throws on any invalid `contractTier` / anatomy.
 * Run: `pnpm contract:generate` (part of `pnpm regen`).
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import type { ComponentMeta, ContractTier } from '../../packages/core/src/types.ts'
import { resolveAnatomy, validateAnatomy, type ResolvedAnatomy } from './anatomy.ts'
import { compileModule, contractClass } from './css.ts'

export const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const COMPONENTS_DIR = join(REPO_ROOT, 'packages/components/src')
export const CONTRACT_JSON = 'packages/css/contract.json'
export const CLASSES_TS = 'packages/css/src/classes.gen.ts'
/** Bumped on a breaking change to the shape of `contract.json` itself (not its content). */
export const CONTRACT_FORMAT = 1

/** Component directories that are not components. */
const NOT_COMPONENTS = new Set(['blocks', 'brand', 'test-utils'])

export interface UnitSource {
  unit: string
  meta: ComponentMeta
  /** Absolute paths of the unit's CSS modules, sorted. */
  modules: string[]
}

export async function loadUnits(dir = COMPONENTS_DIR): Promise<UnitSource[]> {
  const units: UnitSource[] = []
  const dirs = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !NOT_COMPONENTS.has(d.name))
    .map((d) => d.name)
    .sort()
  for (const unit of dirs) {
    const files = readdirSync(join(dir, unit)).sort()
    const metaFile = files.find((f) => f.endsWith('.meta.ts'))
    if (!metaFile) continue
    const mod = (await import(pathToFileURL(join(dir, unit, metaFile)).href)) as {
      meta?: ComponentMeta
    }
    if (!mod.meta) throw new Error(`${unit}/${metaFile} does not export \`meta\``)
    const modules = files.filter((f) => f.endsWith('.module.css')).map((f) => join(dir, unit, f))
    units.push({ unit, meta: mod.meta, modules })
  }
  return units
}

export interface ContractUnit {
  name: string
  tier: ContractTier
  /** Root alias class (`cv-<unit>`); owner decision Q1. */
  alias: string
  /** CSS-module local → contract class. */
  classes: Record<string, string>
  anatomy?: ResolvedAnatomy
}

export interface Contract {
  $comment: string
  format: number
  units: Record<string, ContractUnit>
}

/** CSS-module locals of a unit, merged across its modules and sorted. */
export function unitLocals(u: UnitSource): string[] {
  return [...new Set(u.modules.flatMap((f) => compileModule(f, u.unit).locals))].sort()
}

export function buildContract(units: UnitSource[]): Contract {
  const errors: string[] = []
  const out: Record<string, ContractUnit> = {}
  for (const u of units) {
    const locals = unitLocals(u)
    errors.push(...validateAnatomy(u.unit, u.meta, locals))
    if (!u.meta.contractTier) continue
    out[u.unit] = {
      name: u.meta.name,
      tier: u.meta.contractTier,
      alias: `cv-${u.unit}`,
      classes: Object.fromEntries(locals.map((l) => [l, contractClass(u.unit, l)])),
      ...(u.meta.anatomy ? { anatomy: resolveAnatomy(u.unit, u.meta.anatomy) } : {}),
    }
  }
  if (errors.length) throw new Error(`Invalid markup contract:\n  ${errors.join('\n  ')}`)
  return {
    $comment:
      'Generated by scripts/contract/generate.ts from *.meta.ts + *.module.css. Do not edit.',
    format: CONTRACT_FORMAT,
    units: out,
  }
}

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
const key = (s: string) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : `'${s}'`)

/** The root class of a unit: the anatomy root, else a `root` local, else the local named like the unit. */
export function rootClass(unit: string, u: ContractUnit): string | undefined {
  return u.anatomy?.root.class ?? u.classes['root'] ?? u.classes[unit] ?? u.classes[camel(unit)]
}

export function renderClasses(c: Contract): string {
  const lines = [
    '// Generated by scripts/contract/generate.ts from *.meta.ts + *.module.css. Do not edit.',
    '',
    '/**',
    ' * Contract classes per unit (camelCase unit name): `root` is the root part, `alias` the',
    ' * `cv-<unit>` root alias, every other key a CSS-module local name.',
    ' */',
    'export const classes = {',
  ]
  for (const [unit, u] of Object.entries(c.units)) {
    const root = rootClass(unit, u)
    const entries: [string, string][] = []
    if (root) entries.push(['root', root])
    entries.push(['alias', u.alias])
    for (const [l, cls] of Object.entries(u.classes)) {
      if (l === 'root' || l === 'alias') {
        if (l === 'root' && cls === root) continue
        throw new Error(`${unit}: CSS-module local "${l}" collides with the reserved \`${l}\` key`)
      }
      entries.push([l, cls])
    }
    lines.push(`  ${key(camel(unit))}: {`)
    for (const [k, v] of entries) lines.push(`    ${key(k)}: '${v}',`)
    lines.push('  },')
  }
  lines.push(
    '} as const',
    '',
    '/** A unit key of `classes`, e.g. `button` or `dataTable`. */',
    'export type ContractUnitName = keyof typeof classes',
    '',
  )
  return lines.join('\n')
}

/** Every generated file as `repo-relative path -> content`. */
export async function generateAll(): Promise<Map<string, string>> {
  const contract = buildContract(await loadUnits())
  return new Map([
    [CONTRACT_JSON, `${JSON.stringify(contract, null, 2)}\n`],
    [CLASSES_TS, renderClasses(contract)],
  ])
}

if (import.meta.main) {
  for (const [rel, content] of await generateAll()) {
    const f = join(REPO_ROOT, rel)
    if (!existsSync(dirname(f))) mkdirSync(dirname(f), { recursive: true })
    writeFileSync(f, content)
  }
}
