/**
 * Copies the Cascivo Sans files the site serves from the font build into
 * `apps/site/public/fonts/cascivo-sans/`, and writes their byte sizes for the download list.
 * Only copies existing build output — it never runs the Python font build.
 *
 * Run: `pnpm fonts:site:sync` (part of `pnpm regen`). Checked by `font-site-sync.test.ts`.
 */
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { createHash } from 'node:crypto'
import { join } from 'node:path'
import { FAMILIES } from '../../apps/site/src/marketing/pages/fonts/families.ts'
import { FONT_FILES } from '../../apps/site/src/marketing/pages/cascivo-sans/data.ts'

const ROOT = join(import.meta.dirname, '../..')
const TARGET = join(ROOT, 'apps/site/public/fonts/cascivo-sans')
const SIZES = join(ROOT, 'apps/site/src/marketing/pages/cascivo-sans/sizes.generated.ts')
const COMPARISON_JSON = join(ROOT, 'fonts/cascivo-sans/comparison.json')
const COMPARISON = join(ROOT, 'apps/site/src/marketing/pages/cascivo-sans/comparison.generated.ts')

/** The stylesheets whose @font-face rules load the site's copies. */
export const FONT_FACE_CSS = [
  'apps/site/src/marketing/pages/cascivo-sans/font.css',
  ...FAMILIES.map((f) => `apps/site/src/marketing/font-faces/${f.id}.css`),
]
export const FONT_URL = /url\('(\/fonts\/[^'?]+\.woff2)(?:\?v=[0-9a-f]*)?'\)/g
/** First 10 hex digits of the served file's sha256: changes whenever the bytes do. */
export const fontVersion = (url: string): string =>
  createHash('sha256')
    .update(readFileSync(join(ROOT, 'apps/site/public', url)))
    .digest('hex')
    .slice(0, 10)

mkdirSync(TARGET, { recursive: true })
const wanted = new Set(FONT_FILES.map((f) => f.name))
for (const name of readdirSync(TARGET)) {
  if (!wanted.has(name)) rmSync(join(TARGET, name))
}

// Families with their own pages (/cascivo-mono, -serif, -condensed): their download files, which
// include the Latin web file the header "Aa" picker loads. Sizes feed each page's download list.
const FAMILY_SIZES = join(ROOT, 'apps/site/src/marketing/pages/fonts/sizes.generated.ts')
const familyLines: string[] = []
for (const family of FAMILIES) {
  const dir = join(ROOT, 'apps/site/public/fonts', `cascivo-${family.id}`)
  mkdirSync(dir, { recursive: true })
  const keep = new Set(family.files.map((f) => f.name))
  for (const stale of readdirSync(dir)) if (!keep.has(stale)) rmSync(join(dir, stale))
  for (const f of family.files) {
    copyFileSync(join(ROOT, f.source), join(dir, f.name))
    familyLines.push(`  '${family.id}/${f.name}': ${statSync(join(ROOT, f.source)).size},`)
  }
}
writeFileSync(
  FAMILY_SIZES,
  [
    '// Generated by scripts/fonts/sync-site.ts — do not edit. Run `pnpm fonts:site:sync`.',
    'export const FAMILY_SIZES: Record<string, number> = {',
    ...familyLines,
    '}',
    '',
  ].join('\n'),
)

const lines: string[] = []
for (const f of FONT_FILES) {
  const src = join(ROOT, f.source)
  copyFileSync(src, join(TARGET, f.name))
  lines.push(`  '${f.name}': ${statSync(src).size},`)
}

// Emitted already formatted, so `vp fmt` leaves it alone and re-running this is a no-op.
writeFileSync(
  SIZES,
  [
    '// Generated by scripts/fonts/sync-site.ts — do not edit. Run `pnpm fonts:site:sync`.',
    'export const FONT_SIZES: Record<string, number> = {',
    ...lines,
    '}',
    '',
  ].join('\n'),
)
// The comparison table's figures, so the site build never needs the reference fonts.
// JSON.stringify output is valid TS; the file is on the formatter's ignore list (vite.config.ts).
writeFileSync(
  COMPARISON,
  [
    '// Generated by scripts/fonts/sync-site.ts from fonts/cascivo-sans/comparison.json — do not edit.',
    `export const COMPARISON = ${JSON.stringify(JSON.parse(readFileSync(COMPARISON_JSON, 'utf8')), null, 2)} as const`,
    '',
  ].join('\n'),
)

// The web files keep one URL across rebuilds and /fonts/* is cached for a day (public/_headers), so
// a visitor who loaded an older build kept it: round 3's round Serif dots still showed round 2's
// slab-footed period. Each @font-face url() carries the served file's content hash as `?v=`.
for (const css of FONT_FACE_CSS) {
  const path = join(ROOT, css)
  const before = readFileSync(path, 'utf8')
  const after = before.replace(
    FONT_URL,
    (_, file: string) => `url('${file}?v=${fontVersion(file)}')`,
  )
  if (after !== before) writeFileSync(path, after)
}

console.log(`fonts:site:sync — ${FONT_FILES.length} files → ${TARGET}`)
