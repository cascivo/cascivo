/**
 * Generates crates/cascivo-tui/src/theme_gen.rs: one 15-role sRGB palette per cascivo theme.
 *
 * Variant naming: every theme file scopes exactly one colour scheme (`[data-theme='x']`), so a
 * variant is simply the theme name (`light`, `dark`, `terminal`, ...); there is no `-dark` suffix.
 * Roles resolve through the `var()` alias chain, trying each role's candidate vars in order; a
 * candidate that is not a literal colour (`contrast-color()`, `color-mix`, relative `from`) is skipped.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

export const HEADER = '// @generated by scripts/tui-kit/gen-theme.ts — do not edit\n'

const root = fileURLToPath(new URL('../../', import.meta.url))
const OUT = join(root, 'crates/cascivo-tui/src/theme_gen.rs')

/** Read from build-css.ts text so the generator needs no installed dependencies (lightningcss). */
export const THEME_NAMES: string[] = [
  .../export const THEME_NAMES = \[([^\]]*)\]/
    .exec(readFileSync(join(root, 'scripts/html-kit/build-css.ts'), 'utf8'))![1]!
    .matchAll(/'([\w-]+)'/g),
].map((m) => m[1]!)

/** sRGB in gamma space, channels 0..1, plus alpha. */
export type Rgba = { r: number; g: number; b: number; a: number }
export type Rgb8 = [number, number, number]
/** Role order must match `Role::ALL` in crates/cascivo-tui/src/class.rs. */
export const ROLES = [
  'bg',
  'surface',
  'surface2',
  'border',
  'border_strong',
  'fg',
  'muted',
  'accent',
  'accent_fg',
  'success',
  'warning',
  'danger',
  'info',
  'focus',
  'selection',
] as const
export type RoleName = (typeof ROLES)[number]

/** First var that resolves to a literal wins; `accent` as a candidate means the resolved accent role. */
const CANDIDATES: Record<Exclude<RoleName, 'selection'>, string[]> = {
  bg: ['background'],
  surface: ['surface'],
  surface2: ['surface-2', 'surface-raised'],
  border: ['border'],
  border_strong: ['border-strong'],
  fg: ['foreground'],
  muted: ['text-muted'],
  accent: ['accent', 'primary'],
  accent_fg: ['accent-foreground', 'text-on-accent', 'primary-fg'],
  success: ['success'],
  warning: ['warning'],
  danger: ['destructive', 'error'],
  info: ['info'],
  focus: ['focus-ring', 'accent'],
}

const gamma = (x: number): number => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055)
const linear = (x: number): number => (x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4)

function oklabToLinear(L: number, a: number, b: number): [number, number, number] {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
}

/** oklch → gamma sRGB; out-of-gamut colours keep L and hue and lose chroma (never clipped per channel). */
export function oklchToRgb(L: number, C: number, hDeg: number): [number, number, number] {
  if (L >= 1) return [1, 1, 1]
  if (L <= 0) return [0, 0, 0]
  const h = (hDeg * Math.PI) / 180
  const at = (c: number) => oklabToLinear(L, c * Math.cos(h), c * Math.sin(h))
  const inGamut = (v: number[]) => v.every((x) => x >= -1e-6 && x <= 1 + 1e-6)
  let c = C
  if (!inGamut(at(C))) {
    let lo = 0
    let hi = C
    for (let i = 0; i < 40; i++) {
      const mid = (lo + hi) / 2
      if (inGamut(at(mid))) lo = mid
      else hi = mid
    }
    c = lo
  }
  const [r, g, b] = at(c).map((x) => gamma(Math.min(1, Math.max(0, x)))) as [number, number, number]
  return [r, g, b]
}

const NUM = String.raw`[+-]?(?:\d+\.?\d*|\.\d+)`
const alphaOf = (s: string | undefined): number => {
  if (s === undefined) return 1
  return s.endsWith('%') ? parseFloat(s) / 100 : parseFloat(s)
}

/** Parses a literal colour (oklch, hex, rgb[a], white/black); null when it is not one. */
export function parseColor(raw: string): Rgba | null {
  const v = raw.trim()
  let m = new RegExp(
    String.raw`^oklch\(\s*(${NUM})(%?)\s+(${NUM})\s+(${NUM})(?:deg)?\s*(?:/\s*(${NUM}%?))?\s*\)$`,
    'i',
  ).exec(v)
  if (m) {
    const L = parseFloat(m[1]!) / (m[2] ? 100 : 1)
    const [r, g, b] = oklchToRgb(L, parseFloat(m[3]!), parseFloat(m[4]!))
    return { r, g, b, a: alphaOf(m[5]) }
  }
  m = /^#([0-9a-f]{3,8})$/i.exec(v)
  if (m) {
    let h = m[1]!
    if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join('')
    if (h.length !== 6 && h.length !== 8) return null
    const n = (i: number) => parseInt(h.slice(i, i + 2), 16) / 255
    return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) : 1 }
  }
  m = new RegExp(
    String.raw`^rgba?\(\s*(${NUM}%?)[\s,]+(${NUM}%?)[\s,]+(${NUM}%?)\s*(?:[/,]\s*(${NUM}%?))?\s*\)$`,
    'i',
  ).exec(v)
  if (m) {
    const ch = (s: string) => (s.endsWith('%') ? parseFloat(s) / 100 : parseFloat(s) / 255)
    return { r: ch(m[1]!), g: ch(m[2]!), b: ch(m[3]!), a: alphaOf(m[4]) }
  }
  if (/^white$/i.test(v)) return { r: 1, g: 1, b: 1, a: 1 }
  if (/^black$/i.test(v)) return { r: 0, g: 0, b: 0, a: 1 }
  return null
}

/** Source-over compositing in gamma space (what browsers do for translucent colours). */
export function over(fg: Rgba, bg: Rgba): Rgba {
  const a = fg.a
  return {
    r: fg.r * a + bg.r * (1 - a),
    g: fg.g * a + bg.g * (1 - a),
    b: fg.b * a + bg.b * (1 - a),
    a: 1,
  }
}

export const toRgb8 = (c: Rgba): Rgb8 =>
  [c.r, c.g, c.b].map((x) => Math.round(Math.min(1, Math.max(0, x)) * 255)) as Rgb8

const luminance = (c: Rgba): number =>
  0.2126 * linear(c.r) + 0.7152 * linear(c.g) + 0.0722 * linear(c.b)
const contrast = (a: Rgba, b: Rgba): number => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number]
  return (hi + 0.05) / (lo + 0.05)
}

/** Every `--name: value;` declaration in source order (comments stripped; nested blocks included). */
export function parseDecls(css: string): Map<string, string[]> {
  const out = new Map<string, string[]>()
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const m of clean.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+);/g)) {
    const list = out.get(m[1]!) ?? []
    list.push(m[2]!.replace(/\s+/g, ' ').trim())
    out.set(m[1]!, list)
  }
  return out
}

/** Layered declarations: theme file over the shared tokens. */
export type Decls = Map<string, string[]>[]

/**
 * Resolves `--cascivo-color-<name>` (or a full `--x` name) to a literal. Later declarations win,
 * but a later non-literal (`contrast-color()`, `color-mix`) falls back to the earlier static one.
 */
export function resolveVar(name: string, layers: Decls, depth = 0): Rgba | null {
  if (depth > 12) return null
  for (const layer of layers) {
    const list = layer.get(name)
    if (!list) continue
    for (const value of [...list].reverse()) {
      const c = resolveValue(value, layers, depth + 1)
      if (c) return c
    }
  }
  return null
}

function resolveValue(value: string, layers: Decls, depth: number): Rgba | null {
  const lit = parseColor(value)
  if (lit) return lit
  const m = /^var\(\s*(--[\w-]+)\s*(?:,\s*(.+))?\)$/.exec(value)
  if (!m) return null
  return resolveVar(m[1]!, layers, depth) ?? (m[2] ? resolveValue(m[2], layers, depth + 1) : null)
}

export type Resolved = { colors: Rgb8[]; fallbacks: string[] }

/** Resolves all 15 roles for one theme; throws naming theme and role when one cannot be resolved. */
export function resolveTheme(theme: string, layers: Decls): Resolved {
  const fallbacks: string[] = []
  const got = {} as Record<RoleName, Rgba>
  const bg = resolveVar('--cascivo-color-background', layers)
  if (!bg) throw new Error(`theme ${theme}: role bg does not resolve to a literal colour`)
  for (const role of ROLES) {
    if (role === 'selection') continue
    const cands = CANDIDATES[role]
    let hit: Rgba | null = null
    for (const [i, c] of cands.entries()) {
      // `accent` as a focus candidate reuses the already-resolved accent role.
      hit =
        c === 'accent' && role === 'focus' ? got.accent : resolveVar(`--cascivo-color-${c}`, layers)
      if (hit) {
        if (i > 0) fallbacks.push(`${role}<-${c}`)
        break
      }
    }
    if (!hit && role === 'accent_fg') {
      // contrast-color() is not a literal: pick black or white by contrast against the accent.
      const acc = over(got.accent, over(bg, { r: 0, g: 0, b: 0, a: 1 }))
      const black = { r: 0, g: 0, b: 0, a: 1 }
      const white = { r: 1, g: 1, b: 1, a: 1 }
      hit = contrast(black, acc) >= contrast(white, acc) ? black : white
      fallbacks.push('accent_fg<-contrast')
    }
    if (!hit) throw new Error(`theme ${theme}: role ${role} does not resolve to a literal colour`)
    got[role] = hit
  }
  const solid = (c: Rgba): Rgba => over(c, over(bg, { r: 0, g: 0, b: 0, a: 1 }))
  // Alpha pre-composites over bg; bg itself over black.
  const flat = {} as Record<RoleName, Rgba>
  for (const role of ROLES) if (role !== 'selection') flat[role] = solid(got[role])
  flat.bg = solid(bg)
  flat.selection = over({ ...flat.accent, a: 0.25 }, flat.surface)
  return { colors: ROLES.map((r) => toRgb8(flat[r])), fallbacks }
}

function loadLayers(theme: string): Decls {
  const read = (p: string) => readFileSync(join(root, p), 'utf8')
  return [
    parseDecls(read(`packages/themes/src/${theme}.css`)),
    parseDecls(read('packages/tokens/src/index.css')),
  ]
}

export function generate(): { code: string; fallbacks: Record<string, string[]> } {
  const fallbacks: Record<string, string[]> = {}
  const entries = THEME_NAMES.map((t) => {
    const r = resolveTheme(t, loadLayers(t))
    fallbacks[t] = r.fallbacks
    // One tuple per line keeps the output rustfmt-stable.
    const rows = r.colors.map((c) => `            (${c.join(', ')}),`).join('\n')
    return `    ThemeData {\n        name: "${t}",\n        colors: [\n${rows}\n        ],\n    },`
  })
  const names = THEME_NAMES.map((t) => `    "${t}",`).join('\n')
  const code =
    HEADER +
    '// Role order matches `Role::ALL`: ' +
    ROLES.join(', ') +
    '.\n\n' +
    'use crate::theme::ThemeData;\n\n' +
    `pub(crate) static THEMES: &[ThemeData] = &[\n${entries.join('\n')}\n];\n\n` +
    `pub(crate) static THEME_NAMES: &[&str] = &[\n${names}\n];\n`
  return { code, fallbacks }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { code, fallbacks } = generate()
  writeFileSync(OUT, code)
  for (const [t, f] of Object.entries(fallbacks)) if (f.length) console.log(`${t}: ${f.join(', ')}`)
}
