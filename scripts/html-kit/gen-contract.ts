// Auto emitters

export interface AutoProp {
  name: string
  kind: 'Str' | 'Num' | 'Bool' | 'Enum'
  default?: string
}
export interface AutoTarget {
  cv: string
  unit: string
  children: 'none' | 'text' | 'nodes'
  props: AutoProp[]
}

const VOID = new Set([
  'area',
  'br',
  'col',
  'embed',
  'hr',
  'img',
  'input',
  'link',
  'meta',
  'source',
  'wbr',
])
const rs = (s: string) => JSON.stringify(s)

/** Rust for one auto unit: `fn <mod>(node, cx, out)`. `embeds` are the `embed::` fns that exist. */
export function genAutoFn(t: AutoTarget, u: Unit, embeds: Set<string>): string {
  const a = u.anatomy
  if (!a) throw new Error(`${t.unit}: emit 'auto' needs anatomy`)
  const fail = (m: string): never => {
    throw new Error(`${t.unit}: cannot auto-emit (${m}); use emit: 'manual'`)
  }
  const prop = (n: string) => t.props.find((p) => p.name === n)
  const mod = modName(t.unit)
  const pre: string[] = []
  const lets = new Map<string, string>()
  const need = (name: string, expr: string) => {
    if (!lets.has(name)) {
      lets.set(name, expr)
      pre.push(`    let ${name} = ${expr};`)
    }
    return name
  }
  /** Rust bool expression for a `when` prop expression, or `true`/`false` when constant. */
  const cond = (expr: string): string => {
    const m = /^(!?)([A-Za-z][\w]*)$/.exec(expr.trim()) ?? fail(`when '${expr}'`)
    const p = prop(m[2]!)
    const base = !p
      ? 'false'
      : p.kind === 'Bool'
        ? `node.prop_bool(${rs(p.name)})`
        : `node.prop_str(${rs(p.name)}).is_some_and(|s| !s.is_empty())`
    if (m[1] !== '!') return base
    return base === 'false' ? 'true' : `!${base}`
  }
  const busy = () =>
    prop('loading')?.kind === 'Bool' ? need('busy', 'node.prop_bool("loading")') : 'false'

  const body: string[] = []
  const emitPart = (key: string, p: Part, ind: string): void => {
    const c = p.when ? cond(p.when) : 'true'
    if (c === 'false') return
    let i = ind
    if (c !== 'true') {
      body.push(`${ind}if ${c} {`)
      i = ind + '    '
    }
    const els = Array.isArray(p.element) ? p.element : [p.element]
    let tag: string
    let href = false
    const busyAria = p.aria?.includes('aria-busy') ?? false
    const disabledExpr = () => {
      const d = prop('disabled')?.kind === 'Bool' ? 'node.prop_bool("disabled")' : 'false'
      const b = busyAria ? busy() : 'false'
      return need('disabled', d === 'false' ? b : b === 'false' ? d : `${d} || ${b}`)
    }
    if (els.length === 1) tag = rs(els[0]!)
    else {
      if (key !== 'root' || els.length !== 2 || !els.includes('a') || !prop('href'))
        fail(`polymorphic ${key} <${els.join('|')}>`)
      const other = els.find((e) => e !== 'a')!
      const dis = other === 'button' ? disabledExpr() : 'false'
      need(
        'href',
        `node\n        .prop_str("href")\n        .and_then(|h| safe_url(&h, false))` +
          (dis === 'false' ? '' : `\n        .filter(|_| !${dis})`),
      )
      need('tag', `if href.is_some() { "a" } else { ${rs(other)} }`)
      tag = 'tag'
      href = true
    }
    const tagIsVar = tag === 'tag'
    if (tagIsVar) body.push(`${i}out.push('<');`, `${i}out.push_str(tag);`)
    else body.push(`${i}out.push_str(${rs(`<${els[0]}`)});`)
    if (p.role) body.push(`${i}attr(out, "role", ${rs(p.role)});`)
    for (const [attr, vals] of Object.entries(p.data ?? {})) {
      const name = attr.replace(/^data-/, '')
      const pp = prop(name)
      if (pp?.kind === 'Bool')
        body.push(
          `${i}if node.prop_bool(${rs(name)}) {`,
          `${i}    attr(out, ${rs(attr)}, "true");`,
          `${i}}`,
        )
      else if (pp) {
        const fb = pp.default
        if (fb !== undefined)
          body.push(
            `${i}attr(out, ${rs(attr)}, &node.prop_str(${rs(name)}).unwrap_or_else(|| ${rs(fb)}.into()));`,
          )
        else
          body.push(
            `${i}if let Some(v) = node.prop_str(${rs(name)}) {`,
            `${i}    attr(out, ${rs(attr)}, &v);`,
            `${i}}`,
          )
      } else {
        if (!Array.isArray(vals) || !vals.length) fail(`${attr} has no prop and no values`)
        let e = rs(vals[0]!)
        for (const v of vals.slice(1).reverse()) {
          const vp = prop(v)
          if (vp?.kind !== 'Bool') fail(`${attr} value '${v}' has no bool prop`)
          const c2 = v === 'loading' ? busy() : `node.prop_bool(${rs(v)})`
          e = `if ${c2} { ${rs(v)} } else { ${e} }`
        }
        body.push(`${i}attr(out, ${rs(attr)}, ${e});`)
      }
    }
    for (const ar of p.aria ?? []) {
      if (ar === 'aria-hidden') body.push(`${i}attr(out, "aria-hidden", "true");`)
      else if (ar === 'aria-busy') {
        const b = busy()
        if (b !== 'false')
          body.push(`${i}if ${b} {`, `${i}    attr(out, "aria-busy", "true");`, `${i}}`)
      } else fail(ar)
    }
    const mods = Object.entries(p.modifiers ?? {})
    const cls = key === 'root' ? 'ROOT' : constName(p.local)
    if (!mods.length) body.push(`${i}attr(out, "class", c::${cls});`)
    else {
      body.push(`${i}let mut class = String::from(c::${cls});`)
      for (const [local, m] of mods) {
        const mc = cond(m.when)
        if (mc === 'false') continue
        const push = [`class.push(' ');`, `class.push_str(c::${constName(local)});`]
        if (mc === 'true') body.push(...push.map((s) => i + s))
        else body.push(`${i}if ${mc} {`, ...push.map((s) => `${i}    ${s}`), `${i}}`)
      }
      body.push(`${i}attr(out, "class", &class);`)
    }
    if (href) body.push(`${i}if let Some(h) = &href {`, `${i}    attr(out, "href", h);`, `${i}}`)
    // With an `<a>` alternative, `href` is dropped while disabled, so a disabled tag is the button.
    if (els.includes('button') && prop('disabled')?.kind === 'Bool')
      body.push(`${i}if ${disabledExpr()} {`, `${i}    flag(out, "disabled");`, `${i}}`)
    body.push(`${i}out.push('>');`)
    const isVoid = !tagIsVar && VOID.has(els[0]!)
    if (isVoid && p.children?.length) fail(`void <${els[0]}> with children`)
    for (const ch of p.children ?? []) {
      if (ch === '$slot') {
        if (t.children === 'text') body.push(`${i}esc(out, node.text.as_deref().unwrap_or(""));`)
        else if (t.children === 'nodes') body.push(`${i}emit_children(node, cx, out);`)
        else fail(`$slot but children: none`)
      } else if (ch === '$text') {
        const tp = prop(key) ?? fail(`$text in ${key} has no prop ${key}`)
        body.push(
          `${i}if let Some(v) = node.prop_str(${rs(tp.name)}) {`,
          `${i}    esc(out, &v);`,
          `${i}}`,
        )
      } else if (ch.startsWith('@')) {
        const e = ch.slice(1)
        if (!embeds.has(modName(e))) fail(`no embed::${modName(e)} in emit/embed.rs`)
        body.push(`${i}embed::${modName(e)}(node, cx, out);`)
      } else {
        const child = a.parts?.[ch] ?? fail(`unknown part ${ch}`)
        emitPart(ch, child, i)
      }
    }
    if (!isVoid) {
      if (tagIsVar)
        body.push(`${i}out.push_str("</");`, `${i}out.push_str(tag);`, `${i}out.push('>');`)
      else body.push(`${i}out.push_str(${rs(`</${els[0]}>`)});`)
    }
    if (c !== 'true') body.push(`${ind}}`)
  }
  emitPart('root', a.root, '    ')
  const usesCx = body.some((l) => /\bcx\b/.test(l))
  return [
    `/// \`${t.cv}\` (unit \`${t.unit}\`).`,
    `pub(super) fn ${mod.replace(/^r#/, '')}_auto(node: &Node, ${usesCx ? 'cx' : '_cx'}: &mut Cx, out: &mut String) {`,
    `    use crate::contract::${mod} as c;`,
    ...pre,
    ...body,
    '}',
  ].join('\n')
}

/** Hand-written `pub fn <name>(` items of `emit/embed.rs`. */
export function readEmbeds(src: string): Set<string> {
  return new Set([...src.matchAll(/^pub fn (\w+)\(/gm)].map((m) => m[1]!))
}

export function genAutoRs(targets: AutoTarget[], units: Units, embeds: Set<string>): string {
  const fns = targets.map((t) => genAutoFn(t, units[t.unit]!, embeds))
  const all = fns.join('\n')
  const uses = [
    all.includes('embed::') ? 'use super::embed;' : '',
    all.includes('emit_children(') ? 'use super::emit_children;' : '',
    'use super::NodeExt;',
    'use crate::ast::Node;',
    `use crate::html::{${['attr', 'esc', 'flag', 'safe_url'].filter((f) => all.includes(`${f}(`)).join(', ')}};`,
    'use crate::render::Cx;',
  ].filter(Boolean)
  return [
    CONTRACT_HEADER.replace('from packages/css/contract.json', "from `emit: 'auto'` anatomy"),
    "//! Emitters generated from anatomy with `emit: 'auto'`; conventions in",
    '//! scripts/html-kit/gen-contract.ts. `emit` returns false for every other component.',
    '',
    ...uses,
    '',
    '/// Writes `node` if its component has a generated emitter.',
    'pub fn emit(node: &Node, cx: &mut Cx, out: &mut String) -> bool {',
    '    match node.spec.name {',
    ...targets.map(
      (t) => `        ${rs(t.cv)} => ${modName(t.unit).replace(/^r#/, '')}_auto(node, cx, out),`,
    ),
    '        _ => return false,',
    '    }',
    '    true',
    '}',
    '',
    all,
    '',
  ].join('\n')
}
